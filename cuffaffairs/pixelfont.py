#: Box-outline glyph used for any character without a bitmap.
UNKNOWN = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]

GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
#: Advance per character: glyph plus 1px spacing (before scaling).
ADVANCE = GLYPH_WIDTH + 1


def glyph_for(char: str) -> List[int]:
    """Return the 7 row bitmasks for a character (uppercased; box when unknown)."""
    return GLYPHS.get(char.upper(), UNKNOWN)


def text_width(text: str, scale: int = 1) -> int:
    """Width in pixels of a rendered string (no trailing spacing)."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def each_text_pixel(text: str, plot: Callable[[int, int], None]) -> None:
    """Iterate the lit pixels of a string.

    Calls ``plot(x, y)`` in unscaled glyph space offset by the character
    index — the painter applies scaling.
    """
    for i, char in enumerate(text):
        rows = glyph_for(char)
        for y in range(GLYPH_HEIGHT):
            row = rows[y]
            for x in range(GLYPH_WIDTH):
                if row & (1 << (GLYPH_WIDTH - 1 - x)):
                    plot(i * ADVANCE + x, y)


def draw_text(draw, x: int, y: int, text: str, scale: int, color) -> None:
    """Stamp ``text`` onto a PIL ``ImageDraw`` at (x, y).

    Draws one filled ``scale``x``scale`` rectangle per set bit.
    """

    def plot(gx: int, gy: int) -> None:
        px = x + gx * scale
        py = y + gy * scale
        draw.rectangle((px, py, px + scale - 1, py + scale - 1), fill=color)

    each_text_pixel(text, plot)
